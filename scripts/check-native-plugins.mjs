#!/usr/bin/env node
// Assert that every installed Capacitor plugin with a native Android side is
// actually registered in the two generated Gradle files.
//
// Run manually:  node scripts/check-native-plugins.mjs
// Run in CI:     npm run check:native-plugins
//
// Why this exists. `@capacitor/status-bar` was added to package.json and
// package-lock.json by the v1.13 themes work, and `src/lib/theme.js` imports
// it to restyle the Android status bar for the Dark and Black themes. But
// `npx cap sync android` was never run afterwards, so neither
// android/capacitor.settings.gradle nor android/app/capacitor.build.gradle
// ever learned about it. Those two files are generated, tracked, and were left
// listing four plugins while package.json declared five.
//
// The failure is quiet in every place anyone looks:
//   * `npm ci` succeeds — the JS package is in the lockfile.
//   * `npm run build` succeeds — Rollup resolves the import from node_modules.
//   * `assembleRelease` succeeds — Gradle is only ever told about four plugins,
//     so there is nothing to fail on.
//   * The app installs and runs.
// It surfaces only on a device, at runtime, as a rejected plugin call in a
// dynamic import whose whole design (theme.js:166) is to swallow failures so a
// theme never fails to apply because a native bar could not be restyled. The
// feature simply does not work, and nothing says so.
//
// A plugin that is declared but not registered is a shipped no-op. Whoever adds
// the next native plugin will forget `cap sync` too — the fix is not to
// remember harder, it is to fail the build.
//
// Note that this deliberately checks the COMMITTED Gradle files rather than
// re-running `cap sync`: the point is that what is in git matches what is in
// package.json, because the release APK is built from what is in git.

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const SETTINGS = join(ROOT, 'android', 'capacitor.settings.gradle');
const BUILD = join(ROOT, 'android', 'app', 'capacitor.build.gradle');

const failures = [];

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const deps = Object.keys(pkg.dependencies ?? {});

// Capacitor decides what is a native Android plugin by reading each dependency's
// own package.json for `capacitor.android.src`. Use the same discriminator
// rather than a hand-maintained list, so this cannot drift from what `cap sync`
// would actually do.
const nativePlugins = [];
for (const name of deps) {
  const manifest = join(ROOT, 'node_modules', name, 'package.json');
  if (!existsSync(manifest)) {
    failures.push(
      `${name} is declared in package.json but is not installed.\n` +
      `    Run \`npm ci\` before this check — it cannot tell a native plugin\n` +
      `    from a JS-only package without reading the package's own manifest.`,
    );
    continue;
  }
  let capacitor;
  try {
    capacitor = JSON.parse(readFileSync(manifest, 'utf8')).capacitor;
  } catch {
    continue; // Unreadable manifest is npm's problem to report, not this check's.
  }
  if (capacitor?.android?.src) nativePlugins.push(name);
}

if (!existsSync(SETTINGS) || !existsSync(BUILD)) {
  failures.push(
    'android/capacitor.settings.gradle or android/app/capacitor.build.gradle is missing.\n' +
    '    Both are generated by `npx cap sync android` and both are tracked.',
  );
} else {
  const settings = readFileSync(SETTINGS, 'utf8');
  const build = readFileSync(BUILD, 'utf8');

  for (const name of nativePlugins) {
    // `cap sync` derives the Gradle project name by stripping the scope and
    // prefixing `capacitor-`: @capacitor/status-bar -> capacitor-status-bar.
    const project = `capacitor-${name.replace(/^@[^/]+\//, '').replace(/[^a-z0-9]+/gi, '-')}`;

    if (!settings.includes(`':${project}'`)) {
      failures.push(
        `${name} has a native Android side but is not in android/capacitor.settings.gradle.\n` +
        `    Expected: include ':${project}'\n` +
        `    Run \`npx cap sync android\` and commit both generated Gradle files.`,
      );
    }
    if (!build.includes(`project(':${project}')`)) {
      failures.push(
        `${name} has a native Android side but is not in android/app/capacitor.build.gradle.\n` +
        `    Expected: implementation project(':${project}')\n` +
        `    Run \`npx cap sync android\` and commit both generated Gradle files.`,
      );
    }
  }
}

if (failures.length) {
  console.error(`\nNative plugin check failed (${failures.length} ${failures.length === 1 ? 'issue' : 'issues'}):\n`);
  for (const f of failures) console.error(`  ✗ ${f}\n`);
  console.error(
    'A plugin declared in package.json but absent from the Gradle files is not in\n' +
    'the APK. The JS import resolves, the build passes, and the feature is a no-op\n' +
    'on device.\n',
  );
  process.exitCode = 1;
} else {
  console.log(
    `Native plugin check passed: ${nativePlugins.length} native Capacitor ` +
    `${nativePlugins.length === 1 ? 'plugin is' : 'plugins are'} registered in both Gradle files.`,
  );
}
